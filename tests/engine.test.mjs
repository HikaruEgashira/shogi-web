import test, { after } from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, cp, writeFile, readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { parseState } from '../public/rules.mjs';

await mkdir('.cache/engine-test', { recursive: true });
for (const ext of ['js', 'worker.js', 'wasm']) await cp(`public/engine/yaneuraou.${ext}`, `.cache/engine-test/yaneuraou.${ext}`);
await writeFile('.cache/engine-test/package.json', '{"type":"commonjs"}');
const require = createRequire(import.meta.url);
const factory = require('../.cache/engine-test/yaneuraou.js');
const engine = await factory({ wasmBinary: await readFile('public/engine/yaneuraou.wasm') });
after(() => engine.terminate());
engine.FS.mkdir('/eval');
for (const file of ['nn.bin', 'progress.bin']) engine.FS.writeFile(`/eval/${file}`, await readFile(`public/engine/${file}`));
const lines = [];
engine.addMessageListener(line => lines.push(line));
function request(command, prefix, timeout = 15000) {
  return new Promise((resolve, reject) => {
    const listener = line => {
      if (!line.startsWith(prefix)) return;
      clearTimeout(timer); engine.removeMessageListener(listener); resolve(line);
    };
    const timer = setTimeout(() => { engine.removeMessageListener(listener); reject(Error(`${command} timed out: ${lines.slice(-5)}`)); }, timeout);
    engine.addMessageListener(listener); engine.postMessage(command);
  });
}
await request('usi', 'usiok');
for (const command of ['setoption name EvalDir value /eval', 'setoption name FV_SCALE value 24', 'setoption name USI_Hash value 16', 'setoption name Threads value 1', 'setoption name BookFile value no_book', 'setoption name EnteringKingRule value CSARule27']) engine.postMessage(command);
await request('isready', 'readyok');
async function position(root = 'startpos', moves = []) {
  engine.postMessage(`position ${root}${moves.length ? ` moves ${moves.join(' ')}` : ''}`);
  return parseState(await request('webstate', 'webstate '));
}

test('real micro evaluation loads without architecture or file warnings', async () => {
  assert.ok(lines.some(line => line.includes('loading progress file')));
  assert.ok(!lines.some(line => /mismatch|failed|Error|Warning/.test(line)), lines.join('\n'));
  assert.equal((await position()).legal.length, 30);
});
test('promotions, mandatory promotion and nifu are generated by WASM', async () => {
  const optional = await position('sfen k8/9/4P4/9/9/9/9/9/4K4 b - 1');
  assert.ok(optional.legal.includes('5c5b'));
  assert.ok(optional.legal.includes('5c5b+'));
  const mandatory = await position('sfen k8/4P4/9/9/9/9/9/9/4K4 b - 1');
  assert.ok(mandatory.legal.includes('5b5a+'));
  assert.ok(!mandatory.legal.includes('5b5a'));
  const nifu = await position('sfen 4k4/9/9/9/4P4/9/9/9/4K4 b P 1');
  assert.ok(nifu.legal.includes('P*4e'));
  assert.ok(!nifu.legal.some(move => /^P\*5/.test(move)));
  assert.ok(!nifu.legal.some(move => /^P\*\da/.test(move)));
});
test('pawn-drop mate is prohibited; checkmate has no legal moves', async () => {
  const drop = await position('sfen 4k4/9/3LGL3/9/9/9/9/9/4K4 b P 1');
  assert.ok(!drop.legal.includes('P*5b'));
  assert.ok(drop.legal.includes('P*1e'));
  const mate = await position('sfen 4k4/3LPL3/4G4/9/9/9/9/9/4K4 w - 1');
  assert.ok(mate.check);
  assert.equal(mate.legal.length, 0);
});
test('capture gives unpromoted hand pieces and undo restores exact position', async () => {
  const original = await position();
  const moves = ['7g7f', '3c3d', '8h2b+'];
  const captured = await position('startpos', moves);
  assert.equal(captured.hands.b.B, 1);
  assert.equal(captured.board.get('2b').type, '+B');
  const recaptured = await position('startpos', [...moves, '3a2b']);
  assert.equal(recaptured.hands.w.B, 1);
  assert.equal((await position()).sfen, original.sfen);
});
test('fourfold repetition is a draw, but earlier cycles are not', async () => {
  const cycle = ['5i5h', '5a5b', '5h5i', '5b5a'];
  const root = 'sfen 4k4/9/9/9/9/9/9/9/4K4 b - 1';
  assert.equal((await position(root, [...cycle, ...cycle])).repetition, 0);
  assert.equal((await position(root, [...cycle, ...cycle, ...cycle])).repetition, 3);
});
test('real engine plays 30 legal plies with a finite evaluation', async () => {
  const moves = [];
  for (let ply = 0; ply < 30; ply++) {
    const state = await position('startpos', moves);
    const line = await request('go movetime 30', 'bestmove ');
    const move = line.split(' ')[1];
    assert.ok(state.legal.includes(move), `${ply}: ${line}`);
    moves.push(move);
  }
  assert.ok(lines.some(line => /score cp -?\d+/.test(line)));
});
